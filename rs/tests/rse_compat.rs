fn data_byte(shard: usize, byte: usize) -> u8 {
    (shard as u8).wrapping_mul(31) ^ (byte as u8).wrapping_mul(7) ^ 0x5a
}

fn rse_compat_t<K: Kernel<Gf2p8_11d, StandardBasisLut11d>>() {
    let message: Vec<Gf2p8_11d> = (0..DATA)
        .flat_map(|s| (0..SHARD_LEN).map(move |b| Gf2p8_11d::from(data_byte(s, b))))
        .collect();
    let mut parity = vec![Gf2p8_11d::zero(); PARITY * SHARD_LEN];
    let mut workspace = vec![Gf2p8_11d::zero(); PARITY * SHARD_LEN];
    CodecStandard::<K, 64, 32>::new().encode_systematic_sharded(
        &message,
        &mut parity,
        &mut workspace,
        SHARD_LEN,
    );

    for i in 0..PARITY {
        let ours: Vec<u8> = parity[i * SHARD_LEN..(i + 1) * SHARD_LEN]
            .iter()
            .map(|&x| u8::from(x))
            .collect();
        assert_eq!(
            ours,
            THEIRS[i],
            "parity shard {i} kernel {}",
            std::any::type_name::<K>()
        );
    }
}

#[test]
fn rse_compat() {
    rse_compat_t::<LutKernel<_, StandardBasisLut11d>>();
    #[cfg(native_avx2)]
    rse_compat_t::<Avx2Kernel<_, StandardBasisLut11d>>();
    #[cfg(native_gfni)]
    rse_compat_t::<GfniKernel<_, StandardBasisLut11d>>();
    #[cfg(native_neon)]
    rse_compat_t::<NeonKernel<_, StandardBasisLut11d>>();
}
